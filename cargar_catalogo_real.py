def _tipo_cuenta(nombre: str) -> str:
    """Titulos/agrupadores estan en MAYUSCULAS (T); cuentas de detalle no (D)."""
    return "T" if nombre == nombre.upper() else "D"

#calculo de cuentas contables
def main():
    db: Session = SessionLocal()
    try:
        desactivadas = (
            db.query(CuentaContable)
            .filter(CuentaContable.activa == True)  # noqa: E712
            .update({CuentaContable.activa: False}, synchronize_session=False)
        )

        existentes = {c.codigo: c for c in db.query(CuentaContable).all()}
        nuevas = 0
        actualizadas = 0
        for codigo, nombre in CATALOGO_REAL:
            tipo = _tipo_cuenta(nombre)
            if codigo in existentes:
                cuenta = existentes[codigo]
                cuenta.nombre = nombre
                cuenta.tipo_cuenta = tipo
                cuenta.activa = True
                actualizadas += 1
            else:
                db.add(CuentaContable(codigo=codigo, nombre=nombre, tipo_cuenta=tipo, activa=True))
                nuevas += 1

        db.commit()
    finally:
        db.close()

    print(f"Cuentas desactivadas (catalogo anterior): {desactivadas}")
    print(f"Cuentas reutilizadas/actualizadas (colision de codigo): {actualizadas}")
    print(f"Cuentas nuevas insertadas: {nuevas}")
    print(f"Total en el catalogo nuevo: {len(CATALOGO_REAL)}")


if __name__ == "__main__":
    main()
