def main():
    with engine.begin() as conn:
        conn.execute(text(
            "ALTER TABLE cuentas_contables ADD COLUMN IF NOT EXISTS "
            "tipo_cuenta VARCHAR NOT NULL DEFAULT 'D'"
        ))

    db = SessionLocal()
    try:
        desactivadas = (
            db.query(CuentaContable)
            .filter(CuentaContable.codigo.in_(CODIGOS_PRUEBA_A_DESACTIVAR))
            .update({CuentaContable.activa: False}, synchronize_session=False)
        )

        existentes = {
            codigo for (codigo,) in db.query(CuentaContable.codigo).all()
        }
        nuevas = 0
        for codigo, nombre, tipo_cuenta in PLAN_DE_CUENTAS:
            if codigo in existentes:
                continue
            db.add(CuentaContable(codigo=codigo, nombre=nombre, tipo_cuenta=tipo_cuenta, activa=True))
            nuevas += 1

        db.commit()
    finally:
        db.close()

    print(f"Cuentas de prueba desactivadas: {desactivadas}")
    print(f"Cuentas nuevas insertadas: {nuevas} de {len(PLAN_DE_CUENTAS)} en el plan de cuentas.")


if __name__ == "__main__":
    main()
